#!/usr/bin/env python3
"""gen_fscaa_table.py - FSCAA shader-rewrite targets, hashed exactly like mv_family_table.h.

    python tools/gen_fscaa_table.py <pack> [<pack> ...]

A pack is an spv.zip (of .xsa archives) or a directory holding .xsa archives; packs merge.
Writes src/vklayer/fscaa_table.h:
  kFscaaWire      line3d vertex variants                       (layer 3, wire AA)
  kFscaaLight     light + ground_lights vertex variants         (layer 4, light-point AA)
  kFscaaSpecular  deferred_gbuf fragment variants using reflect (layer 5, specular AA)
  kFscaaAlpha     terrain fragment variants with OpKill         (layer 6, alpha AA)
  kFscaaFamily    every variant -> family index, for the fscaa.debug_tint view
Each list holds candidates; fscaa_patch.h decides per module and refuses what it does not match.
SPDX-License-Identifier: GPL-3.0-or-later
"""
import io
import os
import struct
import sys
import zipfile

OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'vklayer', 'fscaa_table.h')


def iter_pack(pack):
    def from_xsa(fam, blob):
        with zipfile.ZipFile(io.BytesIO(blob)) as z:
            for n in z.namelist():
                if n.endswith('.spv'):
                    yield fam, n, z.read(n)
    if os.path.isdir(pack):
        for root, _, files in os.walk(pack):
            for f in sorted(files):
                if f.endswith('.xsa'):
                    with open(os.path.join(root, f), 'rb') as fh:
                        yield from from_xsa(f[:-4], fh.read())
    else:
        with zipfile.ZipFile(pack) as z:
            for n in z.namelist():
                if n.endswith('.xsa'):
                    yield from from_xsa(os.path.basename(n)[:-4], z.read(n))


def scan(data):
    w = struct.unpack('<%dI' % (len(data) // 4), data[:len(data) // 4 * 4])
    if len(w) < 5 or w[0] != 0x07230203:
        return None
    model, kill, glsl, reflect = -1, False, None, False
    i = 5
    while i < len(w):
        op, n = w[i] & 0xffff, w[i] >> 16
        if n == 0:
            break
        if op == 15 and model < 0:
            model = w[i + 1]
        elif op in (252, 4416):
            kill = True
        elif op == 11:
            glsl = w[i + 1] if b'GLSL.std.450' in b''.join(struct.pack('<I', x) for x in w[i + 2:i + n]) else glsl
        elif op == 12 and glsl is not None and w[i + 3] == glsl and w[i + 4] == 71:
            reflect = True
        i += n
    h = 1469598103934665603
    for x in w:
        h = ((h ^ x) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return dict(model=model, kill=kill, reflect=reflect, hash=h)


def main():
    packs = sys.argv[1:]
    if not packs:
        print(__doc__)
        return 2
    lists = {'Wire': {}, 'Light': {}, 'Specular': {}, 'Alpha': {}}
    family = {}
    names = []
    for p in packs:
        for fam, name, data in iter_pack(p):
            r = scan(data)
            if r is None:
                continue
            if fam not in names:
                names.append(fam)
            family.setdefault(r['hash'], names.index(fam))
            tag = f'{fam}/{name}'
            if fam == 'line3d' and r['model'] == 0:
                lists['Wire'].setdefault(r['hash'], tag)
            elif fam in ('light', 'ground_lights') and r['model'] == 0:
                lists['Light'].setdefault(r['hash'], tag)
            elif fam == 'deferred_gbuf' and r['model'] == 4 and r['reflect']:
                lists['Specular'].setdefault(r['hash'], tag)
            elif fam == 'terrain' and r['model'] == 4 and r['kill']:
                lists['Alpha'].setdefault(r['hash'], tag)
    with open(OUT, 'w', newline='\n') as f:
        f.write('// GENERATED by tools/gen_fscaa_table.py from X-Plane\'s shipped SPIR-V packs - do not edit.\n')
        f.write('// Packs: ' + ', '.join(os.path.basename(os.path.normpath(p)) for p in packs) + '\n')
        f.write('// Regenerate after an X-Plane update changes the shader pack. See fscaa_patch.h.\n')
        f.write('#pragma once\n#include <cstdint>\n#include <cstddef>\n\n')
        for k, rows in lists.items():
            f.write(f'static const uint64_t kFscaa{k}[] = {{\n')
            for h in sorted(rows):
                f.write(f'    0x{h:016x}ull, // {rows[h]}\n')
            if not rows:
                f.write('    0ull,\n')
            f.write('};\n')
            f.write(f'static const size_t kFscaa{k}Count = {len(rows)};\n\n')
        f.write('struct FscaaFamilyRow { uint64_t hash; uint16_t family; };\n')
        f.write('static const FscaaFamilyRow kFscaaFamily[] = {\n')
        for h in sorted(family):
            f.write(f'    {{0x{h:016x}ull, {family[h]}}},\n')
        f.write('};\n')
        f.write(f'static const size_t kFscaaFamilyCount = {len(family)};\n')
        f.write('static const char *const kFscaaFamilyNames[] = {\n')
        for n in names:
            f.write(f'    "{n}",\n')
        f.write('};\n')
        f.write(f'static const size_t kFscaaFamilyNameCount = {len(names)};\n')
    print('fscaa_table.h: ' + ', '.join(f'{k} {len(v)}' for k, v in lists.items()) +
          f', family map {len(family)} variants in {len(names)} families')
    return 0


if __name__ == '__main__':
    sys.exit(main())
